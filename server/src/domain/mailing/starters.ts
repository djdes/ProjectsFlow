// Built-in starting points. They are not stored: the editor opens one as a new template.
// Promo starters promise only what an admin can deliver by hand: plans are granted in
// «Пользователи» (any term); there is no billing, promo codes or automatic discounts — paid
// offers say «ответьте — пришлём счёт». The terms live in the offer fields ({{offer}},
// {{deadline}}) so one edit updates the letter. Urgency comes only from those real terms:
// no invented counters, seats or reviews.
//
