// Детектор префикса «Готово …» / «Сделано …» в тексте задачи из TG-бота: пользователь
// фиксирует УЖЕ ВЫПОЛНЕННУЮ работу, чтобы она попала в трекер (колонка «Готово»), а не
// осталась только в переписке. Чистая функция — легко тестируется.
//
// Правила:
//   • Ключевое слово — ТОЛЬКО в самом начале строки (после необязательных пробелов).
//   • За словом должен идти разделитель (пробел/пунктуация) или конец строки — иначе это
//     часть другого слова («готовность» не считается фиксацией).
//   • Ведущий разделитель после слова («Готово:», «Сделано —») срезается вместе со словом.

const DONE_PREFIX_RE = /^\s*(готово|сделано)(?=$|[\s:;,.!?()«»"'—–-])[\s:;,.!?—–-]*/iu;

export function parseDonePrefix(text: string): { readonly isDone: boolean; readonly rest: string } {
  const m = DONE_PREFIX_RE.exec(text);
  if (!m) return { isDone: false, rest: text };
  return { isDone: true, rest: text.slice(m[0].length) };
}
