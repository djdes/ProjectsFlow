export interface StatsRepository {
  /**
   * Сколько задач текущий пользователь закрыл с начала своих суток.
   *
   * `since` считает клиент (локальная полночь) — сервер живёт в UTC и таймзоны не знает.
   * Считаются и переходы в «на утверждении»: при включённой приёмке «выполнено» исполнителя
   * ведёт туда, и иначе его счётчик всегда был бы нулём.
   */
  completedToday(since: Date): Promise<number>;
}
