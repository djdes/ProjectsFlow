-- Режим сверки коммитов на уровне ПРОСТРАНСТВА.
--
-- Проблема, которую закрываем: настройки уровня пространства расползлись по двум таблицам —
-- приёмка и воркер лежат в `workspaces`, а режим сверки жил в
-- `workspace_assignee_digest_settings.commit_sync_action` (db/144), то есть в настройках
-- ДАЙДЖЕСТА. Из-за этого «выключить сверку во всём пространстве» одним действием было
-- нельзя: приходилось снимать галочки по каждому проекту.
--
-- Семантика (политика «проект → пространство → режим», зеркало worker_enabled):
--   'off'     — сверки в пространстве нет вообще, пер-проектные галочки игнорируются;
--   'propose' — по умолчанию только предлагать закрыть задачу (текущее поведение);
--   'auto'    — по умолчанию переносить задачу в «Готово» самостоятельно.
-- Пер-проектный `project_automation.commit_sync_action` остаётся override'ом: он важнее
-- значения пространства, пока пространство не выключено ('off').
--
-- Дефолт 'propose' повторяет сегодняшнее поведение всех существующих пространств —
-- накат миграции ничего не меняет молча.
ALTER TABLE workspaces
  ADD COLUMN commit_sync_mode VARCHAR(16) NOT NULL DEFAULT 'propose';

-- Индекс не нужен: режим читается по PK пространства (как require_task_approval/worker_enabled).
