-- Приёмка задач руководителем включается ПО УМОЛЧАНИЮ (решение заказчика). В db/150 она
-- была выключена — исходили из того, что включение меняет привычный сценарий команде и
-- должно быть осознанным. Заказчик хочет обратное: приёмка — нормальное состояние, а её
-- отключение — исключение.
--
-- Внимание на охват: это включает приёмку во ВСЕХ существующих пространствах, то есть
-- участники (кроме lead/owner) перестают закрывать задачи напрямую — их «выполнено»
-- отправляет задачу на утверждение. Выключить можно тумблером в настройках пространства.
--
-- Личные «Входящие» приёмку не проходят независимо от флага (см. MoveTask.needsApproval):
-- свою задачу утверждать не у кого.

ALTER TABLE workspaces
  MODIFY COLUMN require_task_approval TINYINT(1) NOT NULL DEFAULT 1;

-- Существующие строки лежат с 0 из db/150 — приводим к новому дефолту.
UPDATE workspaces SET require_task_approval = 1 WHERE require_task_approval = 0;
