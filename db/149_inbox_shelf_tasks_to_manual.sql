-- Полка «В работе» во «Входящих» первой версией ставила задачам статус 'in_progress'.
-- Это ошибка: 'in_progress' — открытая работа pipeline'а, диспетчер-агент считает такие
-- задачи своими (ListMyDispatchedProjects.openTaskCount), и воркер мог бы выполнить задачу,
-- которую человек взял себе. Полка переведена на 'manual' — ветку вне pipeline'а, которую
-- агент не подхватывает никогда.
--
-- Приводим уже отложенные строки к новому смыслу, иначе они выпали бы из полки (она
-- фильтрует по 'manual') и остались бы видимыми воркеру.
--
-- Область: ТОЛЬКО личные входящие. Задачи именованных проектов не трогаем — там
-- 'in_progress' выставляет сам агент, и переводить их в 'manual' значило бы остановить
-- работу. Инбоксы при этом не имеют диспетчера (проверено на проде: 0 строк), поэтому
-- 'in_progress' в них мог появиться только из полки.
--
-- Повторный прогон безопасен: после первого статусов 'in_progress' в инбоксах не остаётся.
UPDATE tasks t
  JOIN projects p ON p.id = t.project_id AND p.is_inbox = 1
  SET t.status = 'manual'
  WHERE t.status = 'in_progress'
    AND t.deleted_at IS NULL;
