-- Кастомные колонки канбана. Команда заводит свои колонки («Ревью», «Тестирование»)
-- в дополнение к встроенным четырём.
--
-- Почему резервные слоты, а не таблица колонок: tasks.status — ENUM, продублированный в
-- ~14 местах кода (домен, zod, дайджесты, TG). Переезд на таблицу означал бы миграцию
-- данных плюс правку всех этих мест; пять заранее заведённых слотов дают ту же
-- продуктовую возможность append-only миграцией и без изменения формы данных.
--
-- Слот «занят» ровно тогда, когда в projects.kanban_settings у него задан label —
-- отдельного флага в БД нет, состояние колонки целиком в JSON-настройках доски.
-- Освобождение колонки переселяет её задачи в 'backlog' (делает use-case, не миграция:
-- на момент наката кастомных колонок ещё нет).
--
-- Append-only: существующие значения и их порядок не трогаем, новые — строго в конец,
-- чтобы numeric storage order уже записанных строк не поехал (см. db/013/038/150).
ALTER TABLE tasks
  MODIFY COLUMN status ENUM(
    'backlog',
    'todo',
    'in_progress',
    'awaiting_clarification',
    'pending_approval',
    'done',
    'manual',
    'custom_1',
    'custom_2',
    'custom_3',
    'custom_4',
    'custom_5'
  ) NOT NULL DEFAULT 'todo';

