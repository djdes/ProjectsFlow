-- Приёмка задач руководителем: сотрудник, «выполняя» задачу, отправляет её НА УТВЕРЖДЕНИЕ,
-- и только руководитель (роль 'lead' из db/147) или владелец переводит её в 'done'.
-- Проблема, которую закрываем: исполнители помечают задачи выполненными, а работа сделана
-- не до конца — и это некому поймать.
--
-- Почему отдельный статус, а не флаг «утверждено» поверх 'done': с флагом задача уже
-- считается выполненной везде (сводки, метрики, колонка «Готово», фильтр hide-done), и
-- руководителю пришлось бы искать непринятую работу среди закрытой.

-- 1. Новое значение статуса. Append-only, как db/147: существующие значения не трогаем,
--    порядок в ENUM повторяет domain TaskStatus (pending_approval стоит перед 'done' —
--    это предпоследний шаг pipeline'а, 'manual' исторически в конце).
ALTER TABLE tasks
  MODIFY COLUMN status ENUM(
    'backlog',
    'todo',
    'in_progress',
    'awaiting_clarification',
    'pending_approval',
    'done',
    'manual'
  ) NOT NULL DEFAULT 'todo';

-- 2. Тумблер приёмки на уровне ПРОСТРАНСТВА. Выключен по умолчанию: включение меняет
--    привычный сценарий всей команде, поэтому это осознанное действие руководителя.
--    Личные входящие не участвуют — свою задачу утверждать не у кого (см. RequestTaskApproval).
ALTER TABLE workspaces
  ADD COLUMN require_task_approval TINYINT(1) NOT NULL DEFAULT 0;

