-- Вход администратора от имени пользователя (админка → «Войти как»). Такая сессия принадлежит
-- пользователю, а impersonator_session_id указывает на сессию администратора, из которой он
-- вошёл: по ней он возвращается обратно, и без неё (вышел, истекла) сессия «от имени»
-- не работает. NULL — обычная сессия.
ALTER TABLE sessions
  ADD COLUMN IF NOT EXISTS impersonator_session_id VARCHAR(64) NULL DEFAULT NULL;
