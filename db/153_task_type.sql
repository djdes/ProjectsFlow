-- Тип задачи: «фича» или «баг». Глобальная колонка, а не кастомное свойство доски —
-- деление на новую функциональность и починку сломанного одинаково осмысленно во всех
-- проектах, и по нему группируются «Входящие».
--
-- NULL = тип не определён (все существующие задачи и всё, что заводят без явного типа).
-- Значения: 'feature' | 'bug'. VARCHAR, а не ENUM: список может дорасти ('chore',
-- 'research'), а ALTER ENUM на большой таблице дороже, чем проверка в домене.
ALTER TABLE tasks
  ADD COLUMN task_type VARCHAR(16) NULL;
